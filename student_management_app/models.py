@receiver(post_save, sender=CustomUser)
def create_user_profile(sender, instance, created, **kwargs):
    if created:
        if instance.user_type == '1':
            AdminHOD.objects.create(admin=instance)
        if instance.user_type == '2':
            Staffs.objects.create(admin=instance)
        if instance.user_type == '3':
            course = Courses.objects.first() or Courses.objects.create(course_name='Default Course')
            session_year = SessionYearModel.objects.first() or SessionYearModel.objects.create(
                session_start_year=date(2024, 1, 1),
                session_end_year=date(2024, 12, 31),
            )
            Students.objects.create(
                admin=instance,
                course_id=course,
                session_year_id=session_year,
                address='',
                profile_pic=None,
                gender='',
            )


@receiver(post_save, sender=CustomUser)
def save_user_profile(sender, instance, **kwargs):
    try:
        if instance.user_type == '1':
            instance.adminhod.save()
    except AdminHOD.DoesNotExist:
        pass
    
    try:
        if instance.user_type == '2':
            instance.staffs.save()
    except Staffs.DoesNotExist:
        pass
    
    try:
        if instance.user_type == '3':
            instance.students.save()
    except Students.DoesNotExist:
        pass
